/**
 * WCAG 2.x relative-luminance contrast ratio, per
 * https://www.w3.org/TR/WCAG21/#dfn-contrast-ratio. Used only by
 * `tokens.contrast.test.ts` to hold the design tokens in `tokens.css`
 * accountable to the "meet WCAG 2.2 AA" requirement (implementation.md
 * section 10.9) as a real, re-checkable assertion rather than a one-off
 * manual calculation.
 */
function srgbChannelToLinear(channel: number): number {
  const c = channel / 255;
  return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
}

function relativeLuminance(hex: string): number {
  const n = Number.parseInt(hex.replace("#", ""), 16);
  const r = (n >> 16) & 255;
  const g = (n >> 8) & 255;
  const b = n & 255;
  return (
    0.2126 * srgbChannelToLinear(r) +
    0.7152 * srgbChannelToLinear(g) +
    0.0722 * srgbChannelToLinear(b)
  );
}

export function contrastRatio(hexA: string, hexB: string): number {
  const lumA = relativeLuminance(hexA);
  const lumB = relativeLuminance(hexB);
  const [lighter, darker] = lumA > lumB ? [lumA, lumB] : [lumB, lumA];
  return (lighter + 0.05) / (darker + 0.05);
}
